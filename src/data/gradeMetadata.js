/**
 * Returns complete international metadata for a given grade
 */
export function getGradeMetadata(gradeId, fallbackDesignation = '') {
  // Normalize key lookup
  const cleanKey = String(gradeId).toLowerCase().trim();

  // Try direct match or partial match
  let meta = gradeEquivalentsMap[cleanKey];

  if (!meta) {
    const foundKey = Object.keys(gradeEquivalentsMap).find((k) => cleanKey.includes(k) || k.includes(cleanKey));
    if (foundKey) meta = gradeEquivalentsMap[foundKey];
  }

  // Generic fallback if not explicitly registered
  if (!meta) {
    return {
      uns: fallbackDesignation.includes('UNS') ? fallbackDesignation : 'UNS Standard Specification',
      wnr: 'W.Nr. Certified Mill Stock',
      en: 'EN 10204 Type 3.1 Traceable',
      jis: 'JIS / Standard Equivalent',
      bs: 'BS / ISO Specification',
      afnor: 'AFNOR Equivalent',
      density: '7.85 - 8.05 g/cm³',
      meltingRange: '1350 - 1450 °C',
      elasticModulus: '190 - 205 GPa',
      thermalConductivity: '15.0 - 25.0 W/m·K',
      heatTreatment: 'Mill Solution Annealed, Normalized, or Stress-Relieved to ASME / ASTM specifications',
      weldability: 'Certified weldable with matching consumable wire/electrodes under ASME Section IX',
    };
  }

  return meta;
}

